<?php
// Файл с функциями для расчёта расходов.
// Функции ничего не выводят, они только возвращают результат через return.
// Сам вывод на страницу делается в index.php.

// Функция делает из числа красивую сумму с валютой.
// Например: 1350 -> "1350 MDL"
function formatSumma(float $summa): string
{
    // round() оставляет не больше 2 знаков после запятой,
    // точка склеивает строки, в конце добавляем валюту
    return round($summa, 2) . " " . VALYUTA;
}

// Функция считает общую сумму всех расходов.
// Если массив пустой, то вернётся 0.
function obshchayaSumma(array $rashody): float
{
    // Переменная-накопитель, сначала в ней 0
    $total = 0;

    // Перебираем все расходы по очереди
    foreach ($rashody as $rashod) {
        // Прибавляем сумму текущего расхода к общей
        $total += $rashod["summa"];
    }

    // Возвращаем то, что накопилось
    return $total;
}

// Функция считает, сколько платит один человек.
// Вызывать её можно только если участников больше нуля,
// потому что на ноль делить нельзя (это проверяется в index.php).
function summaNaCheloveka(float $total, int $uchastniki): float
{
    // Общую сумму делим на количество человек
    return $total / $uchastniki;
}

// Функция сравнивает бюджет с расходами и возвращает сообщение.
function statusByudzheta(float $byudzhet, float $total): string
{
    // Если потратили меньше, чем есть денег
    if ($total < $byudzhet) {
        // Пишем, сколько денег осталось
        return "Бюджета достаточно. Осталось: " . formatSumma($byudzhet - $total);
    // Если потратили ровно столько, сколько было
    } elseif ($total == $byudzhet) {
        // Денег не осталось, но и не перерасходовали
        return "Бюджет использован полностью";
    // Иначе потратили больше, чем было
    } else {
        // Пишем, на сколько вышли за бюджет
        return "Бюджет превышен на " . formatSumma($total - $byudzhet);
    }
}

// Функция ищет самый дорогой расход.
// Если расходов нет, то возвращает null (то есть "ничего").
function samyyBolshoyRashod(array $rashody): ?array
{
    // Пока максимум не найден
    $max = null;

    // Перебираем все расходы
    foreach ($rashody as $rashod) {
        // Если это первый расход или он больше текущего максимума
        if ($max === null || $rashod["summa"] > $max["summa"]) {
            // Запоминаем его как новый максимум
            $max = $rashod;
        }
    }

    // Возвращаем самый большой расход
    return $max;
}

// Функция отбирает крупные расходы: сумма больше или равна $porog.
function krupnyeRashody(array $rashody, float $porog): array
{
    // Пустой массив, сюда будем складывать подходящие расходы
    $result = [];

    // Перебираем все расходы
    foreach ($rashody as $rashod) {
        // Проверяем, что сумма не меньше порога
        if ($rashod["summa"] >= $porog) {
            // Добавляем расход в конец массива
            $result[] = $rashod;
        }
    }

    // Возвращаем отобранные расходы
    return $result;
}
